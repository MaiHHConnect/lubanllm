export function text(language: Language, key: keyof typeof messages.zh): string {
  return messages[language][key];
}

export function locale(language: Language): "zh-CN" | "en-US" {
  return language === "zh" ? "zh-CN" : "en-US";
}

const countryNames = {
  zh: new Intl.DisplayNames([locale("zh")], { type: "region" }),
  en: new Intl.DisplayNames([locale("en")], { type: "region" }),
};

export function localizedCountry(code: string | null | undefined, language: Language): string {
  if (!code || !COUNTRY_CODES.includes(code)) return text(language, "notChosen");
  const flag = String.fromCodePoint(...Array.from(code, letter => letter.charCodeAt(0) + 127397));
  return `${flag} ${countryNames[language].of(code) || code}`;
}

export function assertBilingualCatalog(translations:Record<string,Record<string,string>>=messages, categories:Record<string,Record<string,string>>=domainNames) {
  for(const group of [translations,categories]) {
    if(!group.zh||!group.en||Object.keys(group.zh).toSorted().join("|")!==Object.keys(group.en).toSorted().join("|")) throw new Error("Website gate: Chinese and English keys must match");
    for(const key of Object.keys(group.zh)) {
      const zh=group.zh[key],en=group.en[key];
      if(typeof zh!=="string"||typeof en!=="string"||!zh.trim()||!en.trim()) throw new Error(`Website gate: missing translation ${key}`);
      const placeholders=(value:string)=>(value.match(/\{[a-z]+\}/g)||[]).toSorted().join("|");
      if(placeholders(zh)!==placeholders(en)) throw new Error(`Website gate: mismatched placeholders ${key}`);
      if(key!=="languageChinese"&&/\p{Script=Han}/u.test(en)) throw new Error(`Website gate: untranslated English ${key}`);
    }
  }
}

