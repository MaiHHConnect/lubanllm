REPO = Path(__file__).resolve().parents[1]
PROPOSAL = REPO / 'research/core_identity_field_context_teaching_draft.json'
PROPOSAL_SHA = 'ac90072b80ab9e6931e378f6fe74859319dc4060990549dd6a247cbd40bd1965'


def field_plan(old, result, proposal, *, prepared, session_id, directory):
    """Retain old44 and all63 full records; add fixed13/8 distinct contexts."""
    groups, readonly = copy.deepcopy(proposal['groups']), copy.deepcopy(proposal['regression_validation'])
    validate_field_teaching(groups, readonly)
    failures = {row['id'] for row in result['training']['new_generation'] if not row['passed']}
    if (result.get('passed') is not False or result.get('engineering') != []
            or failures != set(FIELD_PARAPHRASE_IDS.values()) or result['training'].get('promoted') is not False
            or result.get('production_publication') or result.get('recovery') or result.get('known_regression')
            or result['retirement'].get('version') is not None or result['retirement'].get('restored') is not True
            or result['retirement'].get('tensor_sha256') != old['original_tensor_sha256']
            or len(old['source_rows']) != 103 or len(old['superseded_source_ids']) != 13
            or proposal['original_source_rows'] != old['source_rows']
            or proposal['fixed_replay_candidates'] != old['replay_training_candidates']
            or readonly != old['retention_regressions']):
        raise ValueError('Requires exact rejected44 result, originalNone restoration, source103/archive13 and untouched engineering8')
    for key in ('new_training', 'new_validation', 'replay_training', 'replay_validation'):
        original = [row for row in groups[key] if not row['id'].startswith('field-')]
        if original != old['groups_before_original_baseline'][key]:
            raise ValueError('Original44/12/46/16 full records and permissions must remain unchanged')
    plan = copy.deepcopy(old)
    plan.update(sealed=False, status='prepared fixed57 field-context teaching; NOT sealed/run', prepared=prepared,
        session_id=session_id, research_root=str(directory / 'research-storage'), relation_dataset=FIELD_DATASET,
        groups_before_original_baseline=groups, groups_sha256=content_digest(groups),
        retention_regressions=readonly, retention_regressions_sha256=content_digest(readonly), protection_count=71,
        arguments=copy.deepcopy(FIELD_ARGUMENTS), training_checkpoints=list(FIELD_TRAIN_CHECKPOINTS),
        field_proposal_path=str(PROPOSAL), field_proposal_sha256=PROPOSAL_SHA,
        reason='Rejected44 TRAIN passed but field-only name/position/tuner and preexisting18-7 error failed DEV. Teach13 new complete contexts, retain all old gold and permissions; no exact failed-DEV context enters TRAIN.',
        fresh_dev_scope='All original12 are observed development regressions, plus fixed fresh8 full contexts in the same literal task families; not family-independent scientific validation.',
        engineering_scope='Same fixed8 engineering contexts never generated by rejected44, once only after all20 developmental,16 replay and27 known gates; no adaptive retry.',
        prefix_alignment_policy='NEW57 + REPLAY46 + fixed candidates12 =115 TRAIN-only token prefixes/gold+EOS; old102 rows must match. No DEV or engineering tokenization.',
        selection='Independent originalNone maximum832. Qualification markers permit each pool/mandatory task once in that stage; shared training entry independently rechecks all flags on every entry, including resume. Select first two consecutive allNEW57/all flagged replay/EOS/old loss/minNEW2 TRAIN checks, then all20 DEV/16 REPLAYDEV/27 known/8 engineering.',
        snapshot_if_all_pass='All71 unique full obligations =old63 + freshDEV8, unchanged35 readonly including ungeneratedengineering8. Actual backup/original restore/native full reload checks complete71 records and target tensor SHA, two observed identity smoke answers, then actually regenerates all71 closed-book/EOS/gold before publication.',
        planned_counts_if_baseline_qualifies={'new_training': 57, 'new_validation': 20,
            'replay_training': '46 plus4..12 current fixed-pool qualifiers', 'replay_validation': 16},
        exposure_limit='416 NEW optimizer slots /57 yields min7/max8 at832; optimizer batch1, min2 and two consecutive whole TRAIN passes still required. Conservative independent ceiling, not optimality or guaranteed-success evidence.',
        publication='Exact57 dataset only; unchanged103 anchors/exact13 archives,71 retention records and matching immutable journal/artifact/report. No old gold/rights edits; new13 humanFalse/programTrue.',
        repeat_budget_scope='Independent originalNone maximum832. No rejected512 candidate/master/Adam/RNG/session reuse; not an extension of historical640 budget.',
        scope_limit='Finite exact literal field/context teaching and explicit arithmetic correction; no universal identity transfer, semantic-family independence or infinite intelligence claim.',
        training_selection_change_proposed='AllNEW57 plus every current-qualified original-correct replay/EOS and unchanged loss/min2/two consecutive checks; DEV/engineering never affect checkpoint selection.',
        initial_core_version=None, warm_start_candidate=False, maximum_attempts=1, teacher_calls=0,
        implementation_blockers=[], script_sha256=None, execution_manifest=None,
        source_binding='Unsealed fixed57/832 path; TRAIN-only prefix115, independent source review, seal and explicit MODEL GO required.',
        run_descriptor_path=str(REPO / 'research/core_identity_fields_run.json'),
        data_draft_path=str(PROPOSAL), data_draft_sha256=PROPOSAL_SHA,
        previous_field_protocol_path=proposal['prior_protocol']['path'],
        previous_field_protocol_sha256=proposal['prior_protocol']['sha256'],
        previous_field_result_path=proposal['prior_raw_result']['path'],
        previous_field_result_sha256=proposal['prior_raw_result']['sha256'])
    plan['field_teaching_rows'] = [row for row in groups['new_training'] if row['id'] in FIELD_TRAIN_IDS]
    plan['field_teaching_sha256'] = content_digest(plan['field_teaching_rows'])
    validate_protocol_policy(plan)
    for key in ('source_rows', 'source_groups', 'replay_training_candidates', 'superseded_source_ids',
                'required_replay_training_ids', 'original_tensor_sha256', 'operator_audit',
                'engineering_cases', 'engineering_cases_sha256', 'old_known_development_regressions'):
        if plan[key] != old[key]:
            raise ValueError('Original103, pool12, archive13, operator, old27 or engineering8 changed')
    return plan


def prepare():
    descriptor = REPO / 'research/core_identity_fields_preparation.json'
    if descriptor.exists():
        raise FileExistsError('Never overwrite an existing field preparation')
    if digest(PROPOSAL) != PROPOSAL_SHA:
        raise ValueError('Immutable field teaching proposal SHA changed')
    proposal = json.loads(PROPOSAL.read_text())
    paths = [Path(proposal[key]['path']) for key in ('prior_protocol', 'prior_raw_result')]
    if any(digest(path) != proposal[key]['sha256'] for path, key in zip(paths, ('prior_protocol', 'prior_raw_result'))):
        raise ValueError('Prior rejected44 protocol/raw evidence changed')
    old = json.loads(paths[0].read_text())
    check_original_production(old)
    directory = require_storage(old['production_root']) / 'experiments' / ('luban0-identity-fields-preregister-' +
        datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ-') + uuid.uuid4().hex[:8])
    plan = field_plan(old, json.loads(paths[1].read_text()), proposal, prepared=time.time(),
                      session_id=uuid.uuid4().hex[:12], directory=directory)
    plan['historical_files'] += [{'path': str(path), 'sha256': digest(path)} for path in paths + [PROPOSAL]]
    directory.mkdir(mode=0o700, exist_ok=False)
    draft = directory / 'draft-protocol.json'
    write_new(draft, plan)
    record = {'draft_path': str(draft), 'draft_sha256': digest(draft), 'prepared_without_model': True,
        'sealed': False, 'baseline_verified': False, 'pool_count': 12, 'minimum_qualified': 4,
        'mandatory_original_replay_baselines': 2, 'protection_count': 71, 'prefix_count': 115,
        'protocol_descriptor_path': str(REPO / 'research/core_identity_fields_protocol.json')}
    write_new(descriptor, record)
    print(json.dumps(record, ensure_ascii=False))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepare', action='store_true')
    if parser.parse_args().prepare:
        prepare()
    else:
        print(json.dumps({'dataset': FIELD_DATASET, 'arguments': FIELD_ARGUMENTS, 'model_go': False,
                          'sealed': False, 'teacher_calls': 0}))
